-- 4. ADMIN USERS TABLE (Linked directly to auth.users UUID)
CREATE TABLE IF NOT EXISTS public.admin_users (
  id UUID PRIMARY KEY REFERENCES auth.users(id) ON DELETE CASCADE,
  email TEXT NOT NULL UNIQUE,
  full_name TEXT NOT NULL,
  role admin_role_enum NOT NULL DEFAULT 'admin',
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  last_login_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_admin_users_email ON public.admin_users (LOWER(email));
CREATE INDEX IF NOT EXISTS idx_admin_users_role ON public.admin_users (role);

-- 5. PRODUCTS TABLE (Catalog source of truth)
CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug TEXT NOT NULL UNIQUE,
  category TEXT NOT NULL,
  format TEXT NOT NULL,
  language TEXT NOT NULL DEFAULT 'both',
  cover_word TEXT NOT NULL DEFAULT '',
  name TEXT NOT NULL,
  name_ta TEXT NOT NULL,
  short_description TEXT NOT NULL DEFAULT '',
  short_description_ta TEXT NOT NULL DEFAULT '',
  description TEXT NOT NULL DEFAULT '',
  description_ta TEXT NOT NULL DEFAULT '',
  includes JSONB NOT NULL DEFAULT '[]'::jsonb,
  includes_ta JSONB NOT NULL DEFAULT '[]'::jsonb,
  pages INTEGER NOT NULL DEFAULT 1 CHECK (pages >= 1),
  price INTEGER NOT NULL CHECK (price >= 0),
  digital_price INTEGER CHECK (digital_price >= 0),
  physical_price INTEGER CHECK (physical_price >= 0),
  book_type book_type_enum NOT NULL DEFAULT 'both',
  stock_quantity INTEGER NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
  digital_file_path TEXT, -- MUST REMAIN PRIVATE TO BACKEND/ADMIN (NOT EXPOSED IN PUBLIC VIEWS)
  cover_image_url TEXT,
  dimensions TEXT,
  isbn TEXT,
  featured BOOLEAN NOT NULL DEFAULT FALSE,
  version INTEGER NOT NULL DEFAULT 1,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_products_slug ON public.products (slug);
CREATE INDEX IF NOT EXISTS idx_products_category ON public.products (category);
CREATE INDEX IF NOT EXISTS idx_products_book_type ON public.products (book_type);
CREATE INDEX IF NOT EXISTS idx_products_is_active ON public.products (is_active);
CREATE INDEX IF NOT EXISTS idx_products_featured ON public.products (featured);

-- 6. PUBLIC VIEWS (Information Hiding Architecture)

-- View 1: storefront_catalog (Excludes digital_file_path completely to prevent unauthorized discovery)
CREATE OR REPLACE VIEW public.storefront_catalog AS
SELECT
  id,
  slug,
  category,
  format,
  language,
  cover_word,
  name,
  name_ta,
  short_description,
  short_description_ta,
  description,
  description_ta,
  includes,
  includes_ta,
  pages,
  price,
  COALESCE(digital_price, price) AS digital_price,
  physical_price,
  book_type,
  CASE
    WHEN book_type = 'digital' THEN 9999
    ELSE stock_quantity
  END AS stock_quantity,
  cover_image_url,
  dimensions,
  isbn,
  featured,
  created_at
FROM public.products
WHERE is_active = TRUE;

-- View 2: public_store_settings (Excludes sensitive internal admin settings)
CREATE OR REPLACE VIEW public.public_store_settings AS
SELECT
  store_name,
  contact_whatsapp,
  contact_email,
  flat_shipping_rate_inr,
  free_shipping_threshold_inr,
  order_payment_timeout_minutes,
  max_digital_downloads_per_item,
  download_token_validity_days
FROM public.store_settings
WHERE id = 1;

-- 7. UPDATED_AT TRIGGER FUNCTION
CREATE OR REPLACE FUNCTION public.fn_set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
  NEW.updated_at = NOW();
  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_store_settings_updated_at ON public.store_settings;
CREATE TRIGGER trg_store_settings_updated_at
BEFORE UPDATE ON public.store_settings
FOR EACH ROW
EXECUTE FUNCTION public.fn_set_updated_at();

DROP TRIGGER IF EXISTS trg_products_updated_at ON public.products;
CREATE TRIGGER trg_products_updated_at
BEFORE UPDATE ON public.products
FOR EACH ROW
EXECUTE FUNCTION public.fn_set_updated_at();
