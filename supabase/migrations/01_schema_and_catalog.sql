  id SMALLINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
  store_name TEXT NOT NULL DEFAULT 'AUVYRA',
  contact_whatsapp TEXT NOT NULL DEFAULT '+919443187654',
  contact_email TEXT NOT NULL DEFAULT 'contact@auvyra.com',
  flat_shipping_rate_inr INTEGER NOT NULL DEFAULT 60 CHECK (flat_shipping_rate_inr >= 0),
  free_shipping_threshold_inr INTEGER NOT NULL DEFAULT 999 CHECK (free_shipping_threshold_inr >= 0),
  order_payment_timeout_minutes INTEGER NOT NULL DEFAULT 30 CHECK (order_payment_timeout_minutes >= 5),
  max_digital_downloads_per_item INTEGER NOT NULL DEFAULT 5 CHECK (max_digital_downloads_per_item >= 1),
  download_token_validity_days INTEGER NOT NULL DEFAULT 30 CHECK (download_token_validity_days >= 1),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_by UUID REFERENCES auth.users(id)
);

