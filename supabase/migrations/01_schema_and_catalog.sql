-- 2. ENUMS
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'book_type_enum') THEN
    CREATE TYPE book_type_enum AS ENUM ('digital', 'physical', 'both');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'order_payment_status') THEN
    CREATE TYPE order_payment_status AS ENUM ('pending', 'verified', 'failed', 'refunded');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'shipping_status_enum') THEN
    CREATE TYPE shipping_status_enum AS ENUM (
      'not_applicable',
      'pending_verification',
      'processing',
      'dispatched',
      'delivered',
      'returned'
    );
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'admin_role_enum') THEN
    CREATE TYPE admin_role_enum AS ENUM ('super_admin', 'admin');
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'inventory_change_type') THEN
    CREATE TYPE inventory_change_type AS ENUM (
      'order_hold',
      'order_fulfilled',
      'order_cancelled_restored',
      'admin_adjustment',
      'restock'
    );
  END IF;
END $$;

-- 3. STORE SETTINGS TABLE
